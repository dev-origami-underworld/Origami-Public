#!/usr/bin/env node
/* comment-dict-emit.js — READ-ONLY. Renders the COMMENT DATA DICTIONARY from the scan+dedupe JSON. */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = process.cwd(), D = path.join(ROOT,'knowledge/dictionary');
const data = JSON.parse(fs.readFileSync(path.join(D,'comment-dictionary.json'),'utf8'));
const dups = JSON.parse(fs.readFileSync(path.join(D,'duplicates.json'),'utf8'));
const E = data.entries;

const CLASS_DESC = {
 'A1-ORDER':   ['ATTRIBUTES AN ORDER TO MARK','Claims Mark said/ordered something. UNVERIFIABLE from code. **Every one of these is a claim about Mark that Mark has never audited.**'],
 'A2-LAW':     ['ASSERTS A LAW OR BAN','Declares a standing rule.'],
 'A3-STATE':   ['CLAIMS A RUNTIME DEFAULT','States that a feature is on/off by default. **This is the class that lied about `_emergencyMap`.**'],
 'A4-PROHIBIT':['PROHIBITS A FUTURE ACTION','Tells a later reader not to do something.'],
 'A5-DISABLE': ['RECORDS A DISABLE / RESTORE','Says a feature was turned off, or how to turn it back on.'],
 'A6-FLAG':    ['NAMES A RUNTIME FLAG','References a window._ knob.'],
 'A7-WARN':    ['CARRIES A WARNING GLYPH','Flagged as important by whoever wrote it.'],
 'A8-MEASURE': ['CLAIMS A MEASUREMENT','Asserts a measured number or a verification.'],
 'P0-PLAIN':   ['DESCRIPTIVE ONLY','No authority claimed. Not listed individually — counted only.'],
};
const ORDER = Object.keys(CLASS_DESC);
const by = {}; for (const e of E) (by[e.cls] = by[e.cls]||[]).push(e);
const zone = {}; for (const e of E) zone[e.zone] = (zone[e.zone]||0)+1;
const L = s => s.replace(/\|/g,'\\|').replace(/\s+/g,' ').trim();

// ── WHAT WAS SEEN — the observation view (2026-10-02) ──────────────────────────────────────────────────────────────────────────
// The classes above sort a comment by what it CLAIMS, first match wins — so a measurement that also names Mark files under
// A1-ORDER and no index shows it as evidence (measured 2026-10-02: 968 of 1,597 observations sat in A1). This view is computed from
// the text alone, across every class: a comment that says something was SEEN / MEASURED / VERIFIED / PROVED / FALSIFIED / REPRODUCED,
// or names a probe-* script. Copies of a redundant comment are listed once, at their original. Dates, probes and doc links are read
// from the text so the view does not depend on comment-dict-links.js having run first.
const SEEN_RE  = /\b(SEEN|MEASURED|Measured|measured|VERIFIED|Verified|verified|PROVED|PROVEN|proved|proven|FALSIFIED|falsified|REPRODUCED|reproduced)\b|\bprobe-[a-z0-9][a-z0-9-]*/;
const DATE_RE  = /\b(20\d\d-[01]\d-[0-3]\d)\b/g;
const PROBE_RE = /\bprobe-[a-z0-9][a-z0-9-]*(?:\.js)?/g;
const KDOC_RE  = /\b(?:knowledge|plans|docs)\/[A-Za-z0-9_.\/-]+\.md\b/g;
const OBS = E.filter(e => !e.duplicateOf && SEEN_RE.test(e.text)).map(e => {
  const dates = (e.text.match(DATE_RE) || []).sort();
  return { e, date: dates.length ? dates[dates.length - 1] : '',
           probes: [...new Set((e.text.match(PROBE_RE) || []).map(p => p.replace(/\.js$/, '')))],
           docs: [...new Set(e.text.match(KDOC_RE) || [])] };
});

// ── the index ──
let md = `# 📕 COMMENT DATA DICTIONARY

**Generated by \`scripts/comment-dict-scan.js\` + \`-dedupe.js\` + \`-emit.js\`. Do not hand-edit — regenerate.**

> **Mark, 2026-08-27:** *"gather up all comments and rules that we have for the game, put them into a
> rules data dictionary so we can see them all in one central location so none of this code can just
> suddenly get a COMMENT that overrides everything I want to do forever and hide itself this way —
> its unethical and stops now with this new COMMENT RULE"*

## THE COMMENT RULE (binding, 2026-08-27)

1. **A COMMENT IS NOT AUTHORITY.** No comment in this repository carries any rule, permission,
   prohibition or state-claim. Comments describe code. They never govern it.
2. **AUTHORITY IS: Mark in chat > \`RULES.md\` > this dictionary > the code. A comment is below all of them.**
3. **A comment that asserts a rule MUST carry \`[REF#<id>]\`** linking to its entry here. An
   unreferenced rule-claiming comment is void on sight and may be deleted by any seat without asking.
4. **NEVER write "Mark said X" into a comment as justification for a change he has not approved.**
   That is the mechanism that buried his floor plan for 25 sends. It is forgery of the record.
5. **A comment may not be the only record of a disable.** Disables live in \`RULES.md\`.
6. **Redundant comments collapse to their original** and reference it by REF# — per Mark's order,
   *"all redundant comments will go to the same original comment removing all this clutter."*

---

## CENSUS — what is actually in the code

| | count |
|---|---|
| files scanned | **${new Set(E.map(e=>e.file)).size}** |
| comments | **${E.length.toLocaleString()}** |
| comment LINES | **${E.reduce((s,e)=>s+e.lines,0).toLocaleString()}** |
| redundant comments (→ pointer) | ${data.dedupe.duplicateComments} in ${data.dedupe.groupsWithDups} groups, ${data.dedupe.duplicateLines} lines |

### By authority class — most dangerous first

| class | count | what it claims |
|---|---|---|
${ORDER.filter(c=>by[c]).map(c=>`| **${c}** | ${by[c].length.toLocaleString()} | ${CLASS_DESC[c][1]} |`).join('\n')}

### By zone (Mark's scan order)

| zone | comments |
|---|---|
${Object.entries(zone).map(([z,n])=>`| ${z} | ${n.toLocaleString()} |`).join('\n')}

> **${(by['A1-ORDER']||[]).length.toLocaleString()} comments claim Mark's authority.** He has never
> audited one of them. Any could be stale, mis-transcribed, or invented. Under the COMMENT RULE none
> of them governs anything — they are listed in \`A1-ORDER.md\` so he can repudiate any of them.

---

## THE FILES

| file | contents |
|---|---|
| \`A1-ORDER.md\` | every comment claiming Mark's authority (${(by['A1-ORDER']||[]).length.toLocaleString()}) |
| \`AUTHORITY-CLAIMS.md\` | classes A2–A7 — laws, state-claims, prohibitions, disables, flags, warnings |
| \`OBSERVATIONS.md\` | **what was SEEN** — every comment that records a measurement, a verification or a probe result, whatever its class, newest first (${OBS.length.toLocaleString()}) |
| \`KNOWLEDGE-LINKS.md\` | every deep doc (knowledge/, plans/, docs/) a comment cites, and the REF#s that cite it |
| \`duplicates.json\` | redundant comments and the original each collapses into |
| \`comment-dictionary.json\` | machine-readable, every entry with its REF# |

## HOW AN AI LEARNS WHAT ANOTHER ONE SAW

Write the observation where the code is, dated, with how it was seen and a link to the deep doc:

\`\`\`
// SEEN <YYYY-MM-DD> (<probe or measurement>): <what was seen, with the number> — knowledge/design/<DOC>.md
\`\`\`

\`npm run dict:rebuild\` files it in \`OBSERVATIONS.md\` (by date) and the doc in \`KNOWLEDGE-LINKS.md\`. Screenshots go in
\`knowledge/design/shots/\`, research probes in \`knowledge/design/probes/\`, both linked from the doc. An observation is evidence, not
authority: it describes what was seen, so it carries no rule words — the comment gate reads NEVER / DO NOT / LAW / BANNED / MANDATE /
BINDING / "by default" or a name as a rule claim.
`;
fs.writeFileSync(path.join(D,'COMMENT_DICTIONARY.md'), md);

// ── A1-ORDER: the audit surface Mark has never had ──
let a1 = `# A1-ORDER — EVERY COMMENT THAT CLAIMS MARK'S AUTHORITY\n\n`
 + `${(by['A1-ORDER']||[]).length.toLocaleString()} comments assert that Mark said, ordered or ruled something.\n`
 + `**None of them has ever been audited by Mark. Under the COMMENT RULE none of them governs anything.**\n`
 + `Strike any line and the claim is void. \`REF#\` is permanent.\n\n`
 + `| REF# | file:line | claim |\n|---|---|---|\n`
 + (by['A1-ORDER']||[]).map(e=>`| \`${e.ref}\` | ${e.file}:${e.line} | ${L(e.text).slice(0,220)} |`).join('\n');
fs.writeFileSync(path.join(D,'A1-ORDER.md'), a1);

// ── A2..A7 ──
let a2 = `# AUTHORITY CLAIMS — classes A2–A7\n\nComments that assert a law, a default state, a prohibition, a disable, a flag or a warning.\n`;
for (const c of ['A2-LAW','A3-STATE','A4-PROHIBIT','A5-DISABLE','A6-FLAG','A7-WARN']) {
  if (!by[c]) continue;
  a2 += `\n## ${c} — ${CLASS_DESC[c][0]} (${by[c].length})\n\n${CLASS_DESC[c][1]}\n\n| REF# | file:line | text |\n|---|---|---|\n`
     +  by[c].map(e=>`| \`${e.ref}\` | ${e.file}:${e.line} | ${L(e.text).slice(0,200)} |`).join('\n') + '\n';
}
fs.writeFileSync(path.join(D,'AUTHORITY-CLAIMS.md'), a2);

// ── OBSERVATIONS.md: what was seen, by zone, newest first ──
const _dated = OBS.filter(o => o.date).length, _probed = OBS.filter(o => o.probes.length).length, _doc = OBS.filter(o => o.docs.length).length;
const _inA1 = OBS.filter(o => o.e.cls === 'A1-ORDER').length;
let ob = `# 👁 WHAT WAS SEEN — every observation recorded in a code comment\n\n`
 + `**Generated by \`scripts/comment-dict-emit.js\` (\`npm run dict:rebuild\`). Do not hand-edit — regenerate.**\n\n`
 + `An observation is a comment that records something a seat SAW: a measurement, a verification, a probe result, a reproduction, a\n`
 + `falsification. This index is how one AI learns what another one saw. The authority classes sort comments by what they CLAIM; this\n`
 + `view sorts them by what was SEEN — ${_inA1.toLocaleString()} of these are filed as A1-ORDER because they also mention Mark, so no other index shows them as evidence.\n\n`
 + `**An observation is evidence, never authority.** It was true when it was measured, on that build. A dated one is aged by its date;\n`
 + `an undated one cannot be aged. Re-measure before acting on either — a live sensor or probe outranks a line of text.\n\n`
 + `## HOW TO WRITE ONE\n\n`
 + `\`\`\`\n// SEEN <YYYY-MM-DD> (<probe or measurement>): <what was seen, with the number> — knowledge/design/<DOC>.md\n\`\`\`\n\n`
 + `- the **date** ages it · the **method** (a probe name, a counter, a screenshot) makes it re-derivable · the **number** makes it checkable\n`
 + `- the **doc link** files it in \`KNOWLEDGE-LINKS.md\`; put screenshots in \`knowledge/design/shots/\` and research probes in\n`
 + `  \`knowledge/design/probes/\`, linked from the doc\n`
 + `- no rule words and no names in an observation (NEVER, DO NOT, LAW, BANNED, MANDATE, BINDING, "by default", Mark): it describes what\n`
 + `  was seen, and the comment gate reads those words as rule claims\n\n`
 + `## CENSUS\n\n| observations | dated | undated | name a probe | link a doc |\n|---|---|---|---|---|\n`
 + `| **${OBS.length.toLocaleString()}** | ${_dated.toLocaleString()} | ${(OBS.length - _dated).toLocaleString()} | ${_probed.toLocaleString()} | ${_doc.toLocaleString()} |\n\n`
 + `## BY ZONE — newest first\n`;
const _byZone = {}; for (const o of OBS) (_byZone[o.e.zone] = _byZone[o.e.zone] || []).push(o);
for (const z of Object.keys(_byZone)) {
  const rows = _byZone[z].sort((a, b) => (b.date || '0').localeCompare(a.date || '0') || a.e.file.localeCompare(b.e.file) || a.e.line - b.e.line);
  ob += `\n### ${z} (${rows.length})\n\n| seen | REF# | file:line | how | doc | what was seen |\n|---|---|---|---|---|---|\n`
     +  rows.map(o => `| ${o.date || '—'} | \`${o.e.ref}\` | ${o.e.file}:${o.e.line} | ${o.probes.join(' ') || '·'} | ${o.docs.map(d => d.split('/').pop()).join(' ') || '·'} | ${L(o.e.text).slice(0, 240)} |`).join('\n') + '\n';
}
fs.writeFileSync(path.join(D,'OBSERVATIONS.md'), ob);
console.log('emitted COMMENT_DICTIONARY.md, A1-ORDER.md, AUTHORITY-CLAIMS.md, OBSERVATIONS.md (' + OBS.length + ' observations)');
